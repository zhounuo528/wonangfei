const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
exports.run=async context=>{
  const {app,win,store,root}=context;
  assert.equal(app.isPackaged,true);
  assert.ok(app.getAppPath().endsWith('app.asar'));
  const initial=await store.load();assert.equal(initial.state,null,'全新隔离档案应无记录');
  const js=code=>win.webContents.executeJavaScript(code);
  for(let n=0;n<100&&!(await js("document.documentElement.dataset.ready==='true'"));n++)await new Promise(r=>setTimeout(r,80));
  assert.equal(await js("document.getElementById('settings-view').hidden"),false);
  assert.equal(await js("document.getElementById('purchase-amount').value"),'30.00');
  const copy=await js("document.body.textContent");
  assert.ok(!copy.includes('仅换算价格，不会自动扣款'));
  assert.ok(copy.includes('快乐有价，上班也得有价。'));
  await require('./smoke.cjs').run(context);
  await require('./review-smoke.cjs').run(context);
  const {emptyState}=await import(pathToFileURL(path.join(root,'src/model.mjs')).href);
  await store.save(emptyState());
  const result={status:'passed',isPackaged:app.isPackaged,appPath:app.getAppPath(),version:app.getVersion(),platform:process.platform,arch:process.arch,launch:process.env.WORKDAY_LAUNCH_ROUTE??'unspecified',freshProfile:true,baseChecks:32,reviewChecks:9,copyChecked:true,data:'fictional-only',physicalFinderDoubleClick:'not-run: Accessibility unavailable',timestamp:new Date().toISOString()};
  await fs.writeFile(path.join(process.env.WORKDAY_EVIDENCE_DIR,'packaged-launch-result.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
};
